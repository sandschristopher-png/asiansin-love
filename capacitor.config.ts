import type { CapacitorConfig } from '@capacitor/cli';

/**
 * The Android app is a thin native shell around the live site: it opens https://meetin.asia in a WebView, so every
 * deploy to Vercel is what members see (no web assets are bundled). `webDir` still has to exist for `cap sync`;
 * `npm run cap:sync` creates a tiny placeholder in out/ when it is missing (out/ is not committed).
 */

// Meet in Asia's light surface, used for the WebView, the splash and the status bar.
const SURFACE = '#FAF9FC';

// The AdMob app id. This is Google's public SAMPLE id so the app launches before an AdMob account exists. Put Meet in Asia's
// own id (from the AdMob console, "ca-app-pub-XXXXXXXXXXXXXXXX~YYYYYYYYYY") in the ADMOB_APP_ID environment variable and in
// ADMOB_APP_ID in android/gradle.properties (see android/app/build.gradle): a release build refuses to run on the sample id.
const ADMOB_APP_ID = process.env.ADMOB_APP_ID || 'ca-app-pub-3940256099942544~3347511713';

const config: CapacitorConfig = {
  appId: 'asia.meetin.app',
  appName: 'Meet in Asia',
  webDir: 'out',
  server: {
    url: 'https://meetin.asia',
    androidScheme: 'https',
    // Pages the WebView may stay on. Any other link (a partner site, a shared URL) opens in the system browser instead of
    // trapping the member inside the app. XHR and image requests are not affected by this list, only navigation.
    allowNavigation: ['meetin.asia', '*.meetin.asia', '*.supabase.co', 'tiles.openfreemap.org'],
  },
  android: {
    allowMixedContent: false,
    backgroundColor: SURFACE,
  },
  plugins: {
    // Light mode only: dark icons on the light surface, and the bar does not draw over the page.
    StatusBar: {
      overlaysWebView: false,
      style: 'LIGHT',
      backgroundColor: SURFACE,
    },
    // The splash is the brand mark on the light surface (generated by scripts/make-android-assets.mjs); it hides as soon as
    // the site is ready.
    SplashScreen: {
      launchShowDuration: 0,
      launchAutoHide: true,
      backgroundColor: SURFACE,
      androidScaleType: 'CENTER_INSIDE',
      showSpinner: false,
    },
    AdMob: {
      appId: ADMOB_APP_ID,
    },
  },
};

export default config;
